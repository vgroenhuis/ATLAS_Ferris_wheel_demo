#!/usr/bin/env python3
"""gzip every file under <web dir> into <out dir>/<flattened name>.gz and write <out dir>/web_table.h
(URL path, content type, embedded data) for web.c.   usage: pack_web.py <web dir> <out dir>"""
import gzip
import re
import shutil
import sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])
if out.exists():
    shutil.rmtree(out)
out.mkdir(parents=True)
TYPES = {".html": "text/html", ".js": "application/javascript", ".css": "text/css", ".jpg": "image/jpeg",
         ".png": "image/png", ".svg": "image/svg+xml", ".json": "application/json", ".ico": "image/x-icon"}
rows, decls = [], []
for f in sorted(p for p in src.rglob("*") if p.is_file()):
    rel = f.relative_to(src).as_posix()
    flat = Path(rel).name + ".gz"
    with open(out / flat, "wb") as g:
        # mtime=0 and no name: the same input always gives the same bytes
        g.write(gzip.compress(f.read_bytes(), 9, mtime=0))
    sym = "_binary_" + re.sub(r"[^A-Za-z0-9]", "_", flat)
    decls.append(f'extern const uint8_t {sym}_start[] asm("{sym}_start");\nextern const uint8_t {sym}_end[] asm("{sym}_end");')
    rows.append(f'    {{"/{rel}", "{TYPES.get(f.suffix.lower(), "application/octet-stream")}", {sym}_start, {sym}_end}},')
(out / "web_table.h").write_text(
    "// generated by tools/pack_web.py\n#include <stdint.h>\n" + "\n".join(decls) +
    "\nstatic const struct { const char *path, *type; const uint8_t *start, *end; } WEB_FILES[] = {\n" + "\n".join(rows) + "\n};\n")
print(len(rows), "files")
